"""Load device definitions and index them by zigpy model string.

Definition file format (bundled files are generated by tools/generate.js from
zigbee-herdsman-converters; hand-written files use the same shape):

{
  "id": "lumi",
  "name": "...",
  "devices": [
    {
      "models": ["lumi.switch.acn049"],          # zigpy model strings
      "model": "ZNQBKG39LM",                     # vendor model (display only)
      "name": "Aqara Smart wall switch Z1 (double rocker)",
      "settings": [
        {
          "key": "operation_mode_top", "label": "...", "description": "...",
          "group": "Configuration", "control": "select" | "toggle" | "number",
          # Single attribute (readable):
          "target": {"endpoint": 1, "cluster": 64704, "attribute": 512, "type": 32, "manufacturer": 4447},
          "options": [{"label": "Decoupled", "raw": 0}, ...],          # select / toggle (toggle: [off, on])
          # or, for settings Z2M writes as several attributes / byte payloads (write-only):
          "target": null, "options": [{"label": "...", "writes": [{...target, "value": ...}]}],
          # number: "min", "max", "step", "unit", and raw = value * scale + offset
        }
      ]
    }
  ]
}
"""

from __future__ import annotations

import copy
import json
import logging
from pathlib import Path
from typing import Any

from homeassistant.core import HomeAssistant

from .const import USER_DEFINITIONS_DIR

_LOGGER = logging.getLogger(__name__)

BUNDLED_DIR = Path(__file__).parent / "definitions"


def _load_dir(path: Path) -> list[dict[str, Any]]:
    files: list[dict[str, Any]] = []
    if not path.is_dir():
        return files
    for file in sorted(path.glob("*.json")):
        try:
            data = json.loads(file.read_text(encoding="utf-8"))
        except (OSError, ValueError) as err:
            _LOGGER.error("Skipping invalid definition file %s: %s", file, err)
            continue
        if not isinstance(data.get("devices"), list):
            _LOGGER.error("Skipping %s: missing 'devices' list", file)
            continue
        files.append(data)
    return files


def load_definitions(hass: HomeAssistant) -> dict[str, dict[str, Any]]:
    """Return {zigpy model: device entry}. User files in /config override bundled ones."""
    index: dict[str, dict[str, Any]] = {}
    sources = _load_dir(BUNDLED_DIR) + _load_dir(Path(hass.config.path(USER_DEFINITIONS_DIR)))
    for data in sources:
        for device in data["devices"]:
            for model in device.get("models", []):
                index[model] = device
    _LOGGER.debug("Loaded definitions for %d device models", len(index))
    return index


def match_definition(index: dict[str, dict[str, Any]], model: str | None) -> dict[str, Any] | None:
    if not model:
        return None
    return index.get(model)


def find_setting(device_def: dict[str, Any], key: str) -> dict[str, Any] | None:
    return next((s for s in device_def.get("settings", []) if s["key"] == key), None)


def raw_to_ui(setting: dict[str, Any], raw: Any) -> dict[str, Any]:
    """Map a raw attribute value to what the panel shows."""
    if raw is None:
        return {"value": None}
    if setting["control"] == "number":
        scale = setting.get("scale") or 1
        offset = setting.get("offset") or 0
        return {"value": round((raw - offset) / scale, 6)}
    for i, opt in enumerate(setting.get("options", [])):
        if opt.get("raw") == raw:
            return {"value": i}
    return {"value": None, "raw": raw}


def _patch_number(writes: list[dict[str, Any]], patch: dict[str, Any], raw: int) -> list[dict[str, Any]]:
    """Put a raw number into a template write, either as its value or as bytes in its payload."""
    out = copy.deepcopy(writes)
    w = out[patch["write"]]
    if patch.get("scalar"):
        w["value"] = raw
        return out
    width = patch["width"]
    if patch.get("signed") and raw < 0:
        raw += 1 << (8 * width)
    if not 0 <= raw < (1 << (8 * width)):
        raise ValueError(f"Value out of range for a {width}-byte field")
    data = raw.to_bytes(width, "big" if patch["endian"] == "be" else "little")
    start = patch["byte"]
    w["value"] = list(w["value"][:start]) + list(data) + list(w["value"][start + width :])
    return out


def writes_for(setting: dict[str, Any], value: Any) -> list[dict[str, Any]]:
    """Compute the attribute writes for a UI value (option index, or a number)."""
    if setting["control"] == "number":
        lo, hi = setting.get("min"), setting.get("max")
        if (lo is not None and float(value) < lo) or (hi is not None and float(value) > hi):
            raise ValueError(f"Value must be between {lo} and {hi}")
        raw = float(value) * (setting.get("scale") or 1) + (setting.get("offset") or 0)
        template = setting.get("template")
        if template:
            return _patch_number(template["writes"], template["patch"], int(round(raw)))
        target = setting["target"]
        if target["type"] not in (0x38, 0x39, 0x3A):
            raw = int(round(raw))
        return [{**target, "value": raw}]

    options = setting.get("options", [])
    index = int(value)
    if not 0 <= index < len(options):
        raise ValueError(f"Option {index} out of range")
    opt = options[index]
    if "writes" in opt:
        return copy.deepcopy(opt["writes"])
    return [{**setting["target"], "value": opt["raw"]}]


def apply_dynamic(writes: list[dict[str, Any]], ieee: str, now: float) -> list[dict[str, Any]]:
    """Fill device IEEE address / current Unix time slots in payload bytes."""
    ieee_be = bytes.fromhex(ieee.replace(":", ""))
    out = []
    for w in writes:
        slots = w.get("dynamic")
        if not slots:
            out.append(w)
            continue
        data = list(w["value"])
        for slot in slots:
            if slot["kind"] == "ieee":
                chunk = ieee_be
            elif slot["kind"] == "timestamp":
                chunk = int(now).to_bytes(4, "big")
            else:
                raise ValueError(f"Unknown dynamic slot {slot['kind']}")
            if slot["endian"] == "le":
                chunk = chunk[::-1]
            data[slot["byte"] : slot["byte"] + len(chunk)] = list(chunk)
        out.append({**{k: v for k, v in w.items() if k != "dynamic"}, "value": data})
    return out
